const themeMap = new Map(themes.map((theme) => [theme.id, theme]));
const criterionMap = new Map(criteria.map((card) => [card.id, card]));
const penaltyMap = new Map(penalties.map((card) => [card.id, card]));

export function themeById(id: string): Theme {
  const theme = themeMap.get(id);
  if (!theme) throw new Error(`unknown theme ${id}`);
  return theme;
}

export function criterionById(id: string): Criterion {
  const card = criterionMap.get(id);
  if (!card) throw new Error(`unknown criterion ${id}`);
  return card;
}

export function penaltyById(id: string): Penalty {
  const card = penaltyMap.get(id);
  if (!card) throw new Error(`unknown penalty ${id}`);
  return card;
}
